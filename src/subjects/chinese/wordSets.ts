export function getChineseSetsByTier(tier: DifficultyTier): ChineseWordSet[] {
  return BUILTIN_CHINESE_SETS.filter((s) => s.tier === tier);
}

export function getChineseTierWordCounts(): Record<DifficultyTier, number> {
  const counts: Record<DifficultyTier, number> = { 1: 0, 2: 0, 3: 0, 4: 0 };
  for (const set of BUILTIN_CHINESE_SETS) {
    counts[set.tier] += set.words.length;
  }
  return counts;
}

export function getAllBuiltinChineseWords(): Map<string, { word: ChineseTargetWord; set: ChineseWordSet }> {
  const map = new Map<string, { word: ChineseTargetWord; set: ChineseWordSet }>();
  for (const set of BUILTIN_CHINESE_SETS) {
    for (const w of set.words) {
      map.set(w.word, { word: w, set });
    }
  }
  return map;
}
