export function getMathSetsByTier(tier: DifficultyTier): MathQuestSet[] {
  return BUILTIN_MATH_SETS.filter((s) => s.tier === tier);
}

export function getMathTierSkillCounts(): Record<DifficultyTier, number> {
  const counts: Record<DifficultyTier, number> = { 1: 0, 2: 0, 3: 0, 4: 0 };
  for (const set of BUILTIN_MATH_SETS) {
    counts[set.tier] += set.items.length;
  }
  return counts;
}

export function getAllMathSkills(): Map<string, { item: MathSkillItem; set: MathQuestSet }> {
  const map = new Map<string, { item: MathSkillItem; set: MathQuestSet }>();
  for (const set of BUILTIN_MATH_SETS) {
    for (const item of set.items) {
      map.set(item.skillLabel.toLowerCase(), { item, set });
    }
  }
  return map;
}
