export function getWordSetsByTier(tier: DifficultyTier): WordSet[] {
  return BUILTIN_WORD_SETS.filter((s) => s.tier === tier);
}

export function getTierWordCounts(): Record<DifficultyTier, number> {
  const counts: Record<DifficultyTier, number> = { 1: 0, 2: 0, 3: 0, 4: 0 };
  for (const set of BUILTIN_WORD_SETS) {
    counts[set.tier] += set.words.length;
  }
  return counts;
}

export function getAllBuiltinTargetWords(): Map<string, { word: WordSet['words'][number]; set: WordSet }> {
  const map = new Map<string, { word: WordSet['words'][number]; set: WordSet }>();
  for (const set of BUILTIN_WORD_SETS) {
    for (const w of set.words) {
      map.set(w.word.toLowerCase(), { word: w, set });
    }
  }
  return map;
}
